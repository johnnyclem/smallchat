/**
 * SHA-256 (FIPS 180-4), synchronous, over bytes.
 *
 * The inference core (src/core, src/runtime) imports no runtime-specific
 * modules, so it runs unchanged in Node and in browsers. node:crypto is
 * Node-only and WebCrypto's digest is async, so call and proof digests use
 * this small implementation instead. Tests cross-check it against
 * node:crypto.
 */


const rotr = (x: number, n: number): number => (x >>> n) | (x << (32 - n));

/** SHA-256 of `data`, as 64 lowercase hex characters. */
export function sha256Hex(data: Uint8Array): string {
  const bitLength = data.length * 8;
  // Message + 0x80 + zero padding + 64-bit big-endian length, to a multiple of 64 bytes.
  const padded = new Uint8Array(Math.ceil((data.length + 9) / 64) * 64);
  padded.set(data);
  padded[data.length] = 0x80;
  const view = new DataView(padded.buffer);
  view.setUint32(padded.length - 8, Math.floor(bitLength / 0x100000000));
  view.setUint32(padded.length - 4, bitLength >>> 0);

  const h = new Uint32Array([
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
  ]);
  const w = new Uint32Array(64);

  for (let offset = 0; offset < padded.length; offset += 64) {
    for (let i = 0; i < 16; i++) w[i] = view.getUint32(offset + i * 4);
    for (let i = 16; i < 64; i++) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
    }

    let [a, b, c, d, e, f, g, hh] = h;
    for (let i = 0; i < 64; i++) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (hh + S1 + ch + K[i] + w[i]) >>> 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) >>> 0;
      hh = g;
      g = f;
      f = e;
      e = (d + t1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) >>> 0;
    }
    h[0] += a; h[1] += b; h[2] += c; h[3] += d;
    h[4] += e; h[5] += f; h[6] += g; h[7] += hh;
  }

  let hex = '';
  for (const word of h) hex += word.toString(16).padStart(8, '0');
  return hex;
}

const encoder = new TextEncoder();

/**
 * sha256hex(UTF8(domain) || 0x00 || UTF8(part₁) || 0x00 || … || UTF8(partₙ)).
 * The suite's domain-separated digest construction (call digests, proof
 * digests). Parts must not contain U+0000, and must be well-formed UTF-16
 * (a lone surrogate would be silently replaced by U+FFFD when encoded).
 */
export function domainDigest(domain: string, ...parts: string[]): string {
  const chunks = [domain, ...parts].map((part, i) => {
    if (part.includes('\u0000')) {
      throw new TypeError(`domainDigest: part ${i} contains U+0000, which is the separator`);
    }
    if (hasLoneSurrogate(part)) {
      throw new TypeError(`domainDigest: part ${i} contains a lone UTF-16 surrogate`);
    }
    return encoder.encode(part);
  });
  const total = chunks.reduce((n, c) => n + c.length, 0) + chunks.length - 1;
  const bytes = new Uint8Array(total);
  let offset = 0;
  chunks.forEach((chunk, i) => {
    if (i > 0) bytes[offset++] = 0x00;
    bytes.set(chunk, offset);
    offset += chunk.length;
  });
  return sha256Hex(bytes);
}

function hasLoneSurrogate(s: string): boolean {
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c >= 0xd800 && c <= 0xdbff) {
      const next = s.charCodeAt(i + 1);
      if (next >= 0xdc00 && next <= 0xdfff) {
        i++;
        continue;
      }
      return true;
    }
    if (c >= 0xdc00 && c <= 0xdfff) return true;
  }
  return false;
}
